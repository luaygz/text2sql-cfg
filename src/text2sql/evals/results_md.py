"""Sections of the root RESULTS.md, built from the report registry for one preset.

Headline: the preset's reference run per dataset and evidence setting, preferring the held-out
split once it exists. Ablations and sweeps: within one (dataset, split, evidence) context, every
run that changes the preset, each compared with the preset's reference run in that context.
Test-split runs of every preset are counted, so touching the held-out split twice is visible.
"""

from __future__ import annotations

from collections import Counter
from collections.abc import Sequence
from pathlib import Path

from text2sql.evals import markdown as md
from text2sql.evals.figures import SweepPoint, plot_n_sweep
from text2sql.evals.metrics import DIFFICULTY_ORDER, PairedComparison, compare_paired
from text2sql.evals.records import SAFETY_LAYERS, Dataset
from text2sql.evals.registry import Context, RegisteredReport, RunKind, override_label, preferred

EFFORT_ORDER = ("none", "low", "medium", "high", "xhigh", "max")
SPLIT_PREFERENCE = {"test": 2, "all": 1, "dev": 0}
HEADLINE_ROWS: tuple[tuple[Dataset, bool, str], ...] = (
    ("bird_minidev", True, "BIRD Mini-Dev (original)"),
    ("bird_minidev", False, "BIRD Mini-Dev (original)"),
    ("bird_arcwise", True, "Arcwise-Plat-SQL"),
    ("bird_arcwise", False, "Arcwise-Plat-SQL"),
    ("saas", False, "SaaS (synthetic, multi-tenant)"),
)


def render_results_md(
    registry: Sequence[RegisteredReport],
    *,
    preset: str,
    output: Path,
    figures_dir: Path,
    secondary: Sequence[str] = (),
) -> str:
    """RESULTS.md text; also (re)writes the N-sweep figures into `figures_dir`.

    `preset` fills the headline. Each `secondary` preset with runs gets its own section: its
    reference runs, then its ablations and sweeps (used when ablations are cheaper to run on a
    smaller configuration than the headline one).
    """
    entries = [e for e in registry if e.run.config_name == preset]
    lines = [
        "# Results",
        "",
        f"Generated by `text2sql.evals.report.regenerate_results_md` from the report directories "
        f"under `reports/`; do not edit by hand. The headline is the `{preset}` preset "
        f"({len(entries)} runs). Each run link names the run's start time and the git SHA of the "
        "code that produced it.",
        "",
        "Intervals are 95% percentile bootstrap over questions (10,000 resamples, seed 0). "
        "Deltas are paired on the same questions, with exact McNemar p-values. With a few "
        "hundred questions, two configurations a couple of points apart are usually not "
        "distinguishable: read a delta whose interval contains 0 as no measured difference. "
        "Partial runs are labelled in the Run column. Method: "
        "`docs/adr/009-evaluation-methodology.md`.",
        "",
        _test_split_runs(registry),
        "",
        *_headline(entries, output, title=f"## Headline (`{preset}`)"),
        *_evidence_effect(entries),
        *_by_context(preset, entries, output, figures_dir),
    ]
    for other in secondary:
        others = [e for e in registry if e.run.config_name == other]
        if others:
            lines += _headline(others, output, title=f"## The `{other}` preset", saas=False)
            lines += _by_context(other, others, output, figures_dir)
    return "\n".join(lines).rstrip("\n") + "\n"


def _by_context(
    preset: str, entries: Sequence[RegisteredReport], output: Path, figures_dir: Path
) -> list[str]:
    lines: list[str] = []
    for context in sorted({e.context for e in entries}):
        in_context = [e for e in entries if e.context == context]
        lines += _ablations(preset, context, in_context, output)
        lines += _n_sweep(preset, context, in_context, output, figures_dir)
        lines += _effort_sweep(preset, context, in_context, output)
    return lines


def _relative(path: Path, output: Path) -> str:
    return path.resolve().relative_to(output.parent.resolve(), walk_up=True).as_posix()


def _test_split_runs(registry: Sequence[RegisteredReport]) -> str:
    counts = Counter(_context_title(e.context) for e in registry if e.run.split == "test")
    if not counts:
        return "No run of any preset has touched the held-out test split yet."
    listed = "; ".join(f"{title}: {k}" for title, k in sorted(counts.items()))
    return (
        "Runs on the held-out test split, any preset (the protocol allows one per row, after "
        f"the last dev round): {listed}."
    )


def _run_link(entry: RegisteredReport, output: Path) -> str:
    link = f"[{entry.directory.name}]({_relative(entry.directory / 'summary.md', output)})"
    if entry.run.partial:
        answered = entry.summary.overall.n
        link += (
            f" partial: {answered}/{entry.run.questions_planned}, "
            f"{md.cell(entry.run.partial_reason or '')}"
        )
    return link


def _context_title(context: Context) -> str:
    dataset, split, evidence = context
    setting = "n/a" if dataset == "saas" else ("on" if evidence else "off")
    return f"{dataset}, {split} split, evidence {setting}"


def _headline_entry(
    entries: Sequence[RegisteredReport], dataset: Dataset, evidence: bool
) -> RegisteredReport | None:
    matching = [
        e
        for e in entries
        if e.kind == "reference" and (e.run.dataset, e.run.with_evidence) == (dataset, evidence)
    ]
    if not matching:
        return None
    best = max(SPLIT_PREFERENCE.get(e.run.split, -1) for e in matching)
    return preferred([e for e in matching if SPLIT_PREFERENCE.get(e.run.split, -1) == best])


def _headline(
    entries: Sequence[RegisteredReport], output: Path, *, title: str, saas: bool = True
) -> list[str]:
    """One row per dataset and evidence setting; a secondary preset (`saas=False`) lists only
    the rows it has runs for and leaves the SaaS safety summary to the headline preset."""
    rows = []
    saas_entry: RegisteredReport | None = None
    for dataset, evidence, name in HEADLINE_ROWS:
        entry = _headline_entry(entries, dataset, evidence)
        setting = "n/a" if dataset == "saas" else ("with" if evidence else "without")
        if entry is None:
            if saas:
                rows.append([name, setting, "-", "-", "not run yet", "-", "-", "-", "-", "-"])
            continue
        if dataset == "saas":
            saas_entry = entry
        o = entry.summary.overall
        rows.append(
            [
                name,
                setting,
                entry.run.split,
                str(o.n),
                md.rate_ci(o.ex),
                f"{md.pct(o.pass_at_n.value)} (N={entry.run.n_candidates})",
                md.pct(o.selection_accuracy) if o.selection_accuracy is not None else "n/a",
                md.usd(o.cost_per_question_usd),
                f"{md.seconds(o.latency_p50_s)} / {md.seconds(o.latency_p95_s)}",
                _run_link(entry, output),
            ]
        )
    header = [
        "Dataset",
        "Evidence",
        "Split",
        "Questions",
        "EX (95% CI)",
        "pass@N",
        "Selection",
        "Cost / question",
        "Latency p50 / p95",
        "Run",
    ]
    if not rows:
        return []
    lines = [title, "", *md.table(header, rows), ""]
    return lines + (_saas_safety(saas_entry) if saas and saas_entry is not None else [])


def _saas_safety(entry: RegisteredReport) -> list[str]:
    s = entry.summary.safety
    stops = ", ".join(f"{layer} {s.events_by_layer[layer]}" for layer in SAFETY_LAYERS)
    lines = [
        f"SaaS safety: {s.adversarial_questions} adversarial questions; queries stopped per "
        f"layer: {stops}; reached the database: {s.database_violations}.",
        "",
    ]
    a = entry.summary.abstention
    if a is not None:
        precision = md.rate_ci(a.precision) if a.precision else "n/a"
        recall = md.rate_ci(a.recall) if a.recall else "n/a"
        lines += [f"SaaS abstention: precision {precision}, recall {recall}.", ""]
    return lines


def _evidence_effect(entries: Sequence[RegisteredReport]) -> list[str]:
    rows = []
    bird: tuple[tuple[Dataset, str], ...] = (
        ("bird_minidev", "BIRD Mini-Dev (original)"),
        ("bird_arcwise", "Arcwise-Plat-SQL"),
    )
    for dataset, title in bird:
        with_ = _headline_entry(entries, dataset, True)
        without = _headline_entry(entries, dataset, False)
        if with_ is None or without is None or with_.run.split != without.run.split:
            continue
        c = compare_paired(without.questions, with_.questions)
        rows.append(
            [
                title,
                with_.run.split,
                str(c.n),
                md.pct(c.reference_ex),
                md.pct(c.variant_ex),
                md.delta_ci(c),
                md.p_value(c.mcnemar_p),
            ]
        )
    if not rows:
        return []
    header = [
        "Dataset",
        "Split",
        "Paired questions",
        "EX without",
        "EX with",
        "Delta (95% CI)",
        "McNemar p",
    ]
    return ["## Effect of BIRD evidence", "", *md.table(header, rows), ""]


def _ablations(
    preset: str, context: Context, entries: Sequence[RegisteredReport], output: Path
) -> list[str]:
    by_label: dict[str, list[RegisteredReport]] = {}
    for e in entries:
        if e.kind == "ablation":
            by_label.setdefault(override_label(e.run.overrides), []).append(e)
    if not by_label:
        return []
    references = [e for e in entries if e.kind == "reference"]
    reference = preferred(references) if references else None
    rows = []
    if reference is not None:
        rows.append(_ablation_row("all components (reference)", reference, "-", output))
    for label in sorted(by_label):
        entry = preferred(by_label[label])
        comparison: PairedComparison | str = "no reference run"
        if reference is not None:
            comparison = compare_paired(reference.questions, entry.questions)
        rows.append(_ablation_row(md.cell(label), entry, comparison, output))
    header = [
        "Configuration",
        "Questions",
        "EX (95% CI)",
        "Delta EX (paired 95% CI)",
        "McNemar p",
        "pass@N",
        "Cost / question",
        "Run",
    ]
    return [
        f"## Ablations (`{preset}`: {_context_title(context)})",
        "",
        "Each row changes one thing from the reference: a component switched off or one setting.",
        "",
        *md.table(header, rows),
        "",
    ]


def _ablation_row(
    label: str, entry: RegisteredReport, comparison: PairedComparison | str, output: Path
) -> list[str]:
    o = entry.summary.overall
    if isinstance(comparison, PairedComparison):
        delta, p = md.delta_ci(comparison), md.p_value(comparison.mcnemar_p)
        if comparison.n != o.n:
            delta += f" on {comparison.n} paired"
    else:
        delta, p = comparison, "-"
    return [
        label,
        str(o.n),
        md.rate_ci(o.ex),
        delta,
        p,
        md.pct(o.pass_at_n.value),
        md.usd(o.cost_per_question_usd),
        _run_link(entry, output),
    ]


def _sweep_points(
    entries: Sequence[RegisteredReport], kind: RunKind, field: str
) -> list[RegisteredReport]:
    """Preferred run per sweep value, counting the reference run at its own value."""
    groups: dict[str, list[RegisteredReport]] = {}
    for e in entries:
        if e.kind in ("reference", kind):
            groups.setdefault(str(getattr(e.run, field)), []).append(e)
    return [preferred(group) for group in groups.values()]


def _n_sweep(
    preset: str,
    context: Context,
    entries: Sequence[RegisteredReport],
    output: Path,
    figures_dir: Path,
) -> list[str]:
    if not any(e.kind == "n_sweep" for e in entries):
        return []
    points = sorted(
        _sweep_points(entries, "n_sweep", "n_candidates"), key=lambda e: e.run.n_candidates
    )
    difficulties = [
        d for d in DIFFICULTY_ORDER if any(d in p.summary.by_difficulty for p in points)
    ]
    dataset, split, evidence = context
    evidence_tag = "with" if evidence else "no"
    figure = figures_dir / f"n_sweep-{preset}-{dataset}-{split}-{evidence_tag}-evidence.svg"
    plot_n_sweep(
        [
            SweepPoint(p.run.n_candidates, p.summary.overall, p.summary.by_difficulty)
            for p in points
        ],
        difficulties,
        figure,
        title=f"N sweep ({preset}): {_context_title(context)}",
    )
    rows = []
    for p in points:
        o, by = p.summary.overall, p.summary.by_difficulty
        rows.append(
            [
                str(p.run.n_candidates),
                str(o.n),
                md.rate_ci(o.ex),
                *(md.pct(by[d].ex.value) if d in by else "-" for d in difficulties),
                md.pct(o.pass_at_n.value),
                md.usd(o.cost_per_question_usd),
                _run_link(p, output),
            ]
        )
    header = [
        "N",
        "Questions",
        "EX (95% CI)",
        *(f"EX {d}" for d in difficulties),
        "pass@N",
        "Cost / question",
        "Run",
    ]
    return [
        f"## N sweep (`{preset}`: {_context_title(context)})",
        "",
        f"![EX and cost per question against N, by difficulty]({_relative(figure, output)})",
        "",
        *md.table(header, rows),
        "",
    ]


def _effort_sweep(
    preset: str, context: Context, entries: Sequence[RegisteredReport], output: Path
) -> list[str]:
    if not any(e.kind == "effort_sweep" for e in entries):
        return []
    points = sorted(
        _sweep_points(entries, "effort_sweep", "effort"),
        key=lambda e: EFFORT_ORDER.index(e.run.effort),
    )
    rows = []
    for p in points:
        o = p.summary.overall
        rows.append(
            [
                p.run.effort,
                str(o.n),
                md.rate_ci(o.ex),
                md.pct(o.pass_at_n.value),
                md.usd(o.cost_per_question_usd),
                f"{md.seconds(o.latency_p50_s)} / {md.seconds(o.latency_p95_s)}",
                _run_link(p, output),
            ]
        )
    header = [
        "Effort",
        "Questions",
        "EX (95% CI)",
        "pass@N",
        "Cost / question",
        "Latency p50 / p95",
        "Run",
    ]
    return [
        f"## Reasoning-effort sweep (`{preset}`: {_context_title(context)})",
        "",
        *md.table(header, rows),
        "",
    ]
